import { readdir, writeFile } from 'node:fs/promises';
import path from 'node:path';

const appRoot = path.resolve('app');
const output = path.resolve('app/api/_lib/mjic-feature-routes.generated.ts');
const routes = [];

async function scan(directory) {
  for (const entry of await readdir(directory, { withFileTypes: true })) {
    const fullPath = path.join(directory, entry.name);
    if (entry.isDirectory()) {
      await scan(fullPath);
      continue;
    }
    if (!entry.isFile() || !['page.tsx', 'route.ts'].includes(entry.name)) continue;
    const relative = path.relative(appRoot, fullPath).split(path.sep).join('/');
    const segments = relative.split('/');
    segments.pop();
    if (segments.at(-1) === 'api' && entry.name === 'page.tsx') continue;
    const routeSegments = segments.filter((segment) => !segment.startsWith('(') && !segment.startsWith('@'));
    const route = `/${routeSegments.join('/')}`;
    routes.push(route === '/' ? '/' : route.replace(/\/$/, ''));
  }
}

await scan(appRoot);
routes.sort();
const contents = `// Generated by scripts/sync-features.mjs; do not edit by hand.\nexport const MJIC_DETECTED_ROUTE_PATHS: readonly string[] = ${JSON.stringify(routes, null, 2)};\n`;
await writeFile(output, contents, 'utf8');
console.log(`Registered ${routes.length} app pages and API routes.`);
